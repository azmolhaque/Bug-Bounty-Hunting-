"""
Phase 6 report generation.

Produces triager-grade vulnerability reports in Markdown from confirmed findings.
Uses Claude API if available; falls back to a structured template.
Report files land in results/<target>/findings/
"""
import json
import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

log = logging.getLogger(__name__)

TEMPLATE = """\
# {title}

**Severity:** {severity} (CVSS {cvss_score})
**CVSS Vector:** `{cvss_vector}`
**Target:** `{target}`
**Vulnerability Class:** {vuln_class}
**Finding ID:** {id}
**Date:** {date}

---

## Summary

{summary}

---

## Severity

**CVSS 3.1:** `{cvss_vector}` — **{cvss_score}** ({severity})

**Business Impact:** {business_impact}

---

## Steps to Reproduce

{repro_steps}

---

## Proof

```
{evidence}
```

---

## Impact

{impact}

---

## Remediation

{remediation}

---

## References

- {references}

---

*Report generated by Bug Bounty Agent v2.0*
"""


def generate_report(
    finding: dict,
    output_dir: Path,
    claude_client=None,
    target_context: str = "",
) -> Optional[Path]:
    """
    Write a full vulnerability report to output_dir/findings/<id>.md.
    Returns the report path, or None on failure.
    """
    fid     = finding.get("id", "UNKNOWN")
    title   = _build_title(finding)
    sev     = finding.get("severity", "unknown").capitalize()
    target  = finding.get("target", "")
    cls     = finding.get("vuln_class", "")
    summary = finding.get("summary", "No summary provided.")
    impact  = finding.get("impact", "Not specified.")
    remed   = finding.get("remediation", "Refer to vendor for remediation guidance.")
    cvss_v  = finding.get("cvss_vector", "N/A")
    cvss_s  = finding.get("cvss_score", "N/A")
    evidence= finding.get("evidence", "No evidence captured.")
    steps   = finding.get("repro_steps", [])
    refs    = finding.get("references", ["OWASP Top 10", "CWE"])

    output_dir.mkdir(parents=True, exist_ok=True)

    if claude_client and claude_client.enabled:
        log.info("Generating report for %s with Claude", fid)
        try:
            report_text = claude_client.generate_report(finding, target_context)
        except Exception as e:
            log.warning("Claude report failed: %s — using template", e)
            report_text = _fill_template(
                fid, title, sev, target, cls, summary, impact, remed,
                cvss_v, str(cvss_s), evidence, steps, refs,
            )
    else:
        report_text = _fill_template(
            fid, title, sev, target, cls, summary, impact, remed,
            cvss_v, str(cvss_s), evidence, steps, refs,
        )

    safe_name = f"{fid}-{cls.lower().replace(' ', '-')}.md"
    report_path = output_dir / safe_name

    try:
        report_path.write_text(report_text)
        log.info("Report written: %s", report_path)
        return report_path
    except Exception as e:
        log.error("Failed to write report %s: %s", report_path, e)
        return None


def _build_title(finding: dict) -> str:
    cls    = finding.get("vuln_class", "Vulnerability")
    target = finding.get("target", "").replace("https://", "").replace("http://", "").split("/")[0]
    impact = finding.get("impact", "")
    # Title: [Class] [short impact] via [location]
    if impact:
        short_impact = impact.split(".")[0][:60]
        return f"[{cls}] {short_impact} on {target}"
    return f"[{cls}] Confirmed Vulnerability on {target}"


def _fill_template(
    fid, title, sev, target, cls, summary, impact, remed,
    cvss_v, cvss_s, evidence, steps, refs,
) -> str:
    repro = "\n".join(f"{i+1}. {s}" for i, s in enumerate(steps)) if steps else "1. Manual reproduction required — see evidence."
    biz   = f"Confirmed {cls} on {target} — attacker can {impact[:100]}" if impact else f"Confirmed {cls} — see impact section."
    refs_text = "\n- ".join(refs) if refs else "OWASP Top 10"
    date  = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    return TEMPLATE.format(
        id=fid, title=title, severity=sev, target=target, vuln_class=cls,
        summary=summary, impact=impact, remediation=remed,
        cvss_vector=cvss_v, cvss_score=cvss_s,
        evidence=evidence[:2000], repro_steps=repro,
        business_impact=biz, references=refs_text, date=date,
    )
